import styles from "../css.js";
import { escapeHtml, safeArray, renderSection } from "../helper.js";

const badge = (text, cls = "") => `<span class="badge ${cls}">${escapeHtml(text)}</span>`;

const scoreCard = (analysis) => {
    const score = Number(analysis.matchScore || 0);

    return `
        <div class="score-card">
            <div class="score-badge">${score}</div>
            <div class="score-text">
                <h1>Resume Analysis Report</h1>
                <p>ATS-style review with strengths, weaknesses, missing keywords, and a practical roadmap.</p>
            </div>
        </div>
    `;
};

const listSection = (title, items = [], type = "bullet") => {
    const arr = safeArray(items);
    if (!arr.length) return "";

    const content = type === "badge"
        ? `<div class="badge-row">${arr.map(item => badge(item)).join("")}</div>`
        : `<ul class="bullet-list">${arr.map(item => `<li>${escapeHtml(item)}</li>`).join("")}</ul>`;

    return renderSection(title, content);
};

const skillGapSection = (analysis) => {
    const items = safeArray(analysis.skillGap);
    if (!items.length) return "";

    const content = items.map(item => {
        const skill = typeof item === "string" ? item : item.skill;
        const severity = typeof item === "object" ? item.severity : "medium";

        return `
            <div class="callout">
                <h3>${escapeHtml(skill || "")} <span class="badge">${escapeHtml(severity || "medium")}</span></h3>
            </div>
        `;
    }).join("");

    return renderSection("Skill Gap", content);
};

const roadmapSection = (analysis) => {
    const items = safeArray(analysis.learningRoadmap);
    if (!items.length) return "";

    return renderSection(
        "Learning Roadmap",
        `<ul class="bullet-list">${items.map(item => `<li>${escapeHtml(item)}</li>`).join("")}</ul>`
    );
};

export const generateAnalysisHTML = (analysis) => `
<!DOCTYPE html>
<html>
<head>
    <meta charset="UTF-8" />
    <style>${styles}</style>
</head>
<body>
    <div class="page">
        ${scoreCard(analysis)}
        ${renderSection("Executive Summary", `<p class="summary">${escapeHtml(analysis.summary || "")}</p>`)}
        ${listSection("Strengths", analysis.strengths)}
        ${listSection("Weaknesses", analysis.weaknesses)}
        ${skillGapSection(analysis)}
        ${listSection("Matched Keywords", analysis.keywordMatch, "badge")}
        ${listSection("Missing Keywords", analysis.missingKeywords, "badge")}
        ${listSection("ATS Tips", analysis.atsTips)}
        ${roadmapSection(analysis)}
        <div class="footer-note">Generated by DevCane AI Resume Analyzer</div>
    </div>
</body>
</html>
`;